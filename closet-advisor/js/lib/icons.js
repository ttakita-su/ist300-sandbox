/**
 * @param {keyof typeof ICONS} name
 * @param {{ label?: string, className?: string }} [opts] label makes the icon announced
 */
export function icon(name, opts = {}) {
  const body = ICONS[name] ?? ICONS.info;
  const cls = opts.className ? `icon ${opts.className}` : 'icon';
  if (opts.label) {
    const label = String(opts.label).replace(/[<>&"]/g, '');
    return raw(`<svg class="${cls}" viewBox="0 0 24 24" role="img" aria-label="${label}">${body}</svg>`);
  }
  return raw(`<svg class="${cls}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${body}</svg>`);
}

export const iconNames = Object.keys(ICONS);

/** Icon for a product category. */
export function categoryIcon(category, opts) {
  return icon(category === 'watch' ? 'watch' : category === 'clothing' ? 'shirt' : 'sneaker', opts);
}
