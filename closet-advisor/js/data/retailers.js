const sizes = (values, priceMinor, outOfStock = [], low = []) =>
  values.map((value) => ({
    value,
    system: 'US-M',
    priceMinor,
    stock: outOfStock.includes(value) ? 'out_of_stock' : low.includes(value) ? 'low_stock' : 'in_stock',
  }));

const alpha = (values, priceMinor, outOfStock = []) =>
  values.map((value) => ({ value, system: 'ALPHA', priceMinor, stock: outOfStock.includes(value) ? 'out_of_stock' : 'in_stock' }));

const waist = (values, priceMinor, outOfStock = []) =>
  values.map((value) => ({ value, system: 'WAIST-INSEAM', priceMinor, stock: outOfStock.includes(value) ? 'out_of_stock' : 'in_stock' }));

const oneSize = (priceMinor, stock = 'in_stock') => [{ value: 'OS', system: 'ONE-SIZE', priceMinor, stock }];

